/** Formulas that really are formula-shaped (the board draws these). */
function formulaLooksReal(formula: string): boolean {
  return /[=\\$^_]/.test(formula) || /[→×±π√∫∑αβγθΔ]/.test(formula);
}

// ─────────────────────────────────────────────────────────────────────────────
// Row assembly: fixed priority chains over the topic's own fields, each string
// used at most once per card (so no idea is listed twice on the same card).
// ─────────────────────────────────────────────────────────────────────────────
const FIELD_ORDER: (keyof ConceptRecord)[] = [
  "summary",
  "importantConcepts",
  "formulas",
  "specificConditions",
  "keyPoints",
  "confusion",
  "examples",
  "specialNotes",
  "importantNotes",
  "importantStatements",
  "examShortTricks",
  "examNotes",
  "practiceQuestions",
  "practice",
  "importantTasks",
  "universalFacts",
  "bounds",
  "notes",
];

interface RowDraft {
  label: string;
  kind?: "formula";
  items: string[];
  figureIdea?: boolean;
}

function buildRows(c: ConceptRecord): {
  rows: HomeRailFileRow[];
  mapIdeas: string[];
} {
  const used = new Set<string>();
  /** Field values are arrays of strings, or a single string (e.g. `summary`). */
  const fieldList = (field: keyof ConceptRecord): string[] => {
    const v = c[field];
    if (typeof v === "string") return [v];
    return arr(v);
  };
  const take = (field: keyof ConceptRecord, n: number, per = 420): string[] => {
    const out: string[] = [];
    for (const raw of fieldList(field)) {
      if (out.length >= n) break;
      const t = raw.trim();
      if (!t || t.startsWith(TODO) || used.has(t)) continue;
      used.add(t);
      out.push(clip(t, per));
    }
    return out;
  };
  const takeAny = (n: number, per = 420): string[] => {
    const out: string[] = [];
    for (const field of FIELD_ORDER) {
      if (out.length >= n) break;
      out.push(...take(field, n - out.length, per));
    }
    return out;
  };
  /** First non-empty chain result. */
  const chain = (
    steps: Array<() => string[]>,
    n: number,
  ): string[] => {
    for (const step of steps) {
      const got = step();
      if (got.length > 0) return got;
    }
    return [];
  };

  const mcqText = (n: number): string[] => {
    // MCQs / exercises are object arrays — read them raw, `arr()` would drop
    // every entry. Their shapes differ (options vs steps) but all carry a
    // question and an answer, which is all the drill row shows.
    const list = [c.mcs, c.mcqs, c.exercises].flatMap((v) =>
      Array.isArray(v) ? (v as Record<string, unknown>[]) : [],
    );
    const out: string[] = [];
    for (const mc of list) {
      if (out.length >= n) break;
      const q = text(mc?.question);
      const a = text(mc?.answer);
      if (!q || used.has(q)) continue;
      used.add(q);
      out.push(clip(`${q} → ${a}`, 300));
    }
    return out;
  };

  const drafts: RowDraft[] = [
    {
      label: "Concept",
      figureIdea: true,
      items: chain(
        [() => take("summary", 1, 420), () => take("importantConcepts", 1), () => take("notes", 1, 420)],
        1,
      ),
    },
    {
      label: "Formula",
      kind: "formula",
      items: chain(
        [
          () => take("formulas", 3, 220),
          () => take("specificConditions", 2, 220),
          () => take("importantStatements", 2, 220),
          () => take("keyPoints", 2, 220),
          () => takeAny(2, 220),
        ],
        2,
      ),
    },
    {
      label: "Conditions",
      items: chain(
        [
          () => take("specificConditions", 2, 380),
          () => take("confusion", 2, 380),
          () => take("specialNotes", 2),
          () => take("bounds", 2, 300),
          () => take("importantNotes", 2),
        ],
        2,
      ),
    },
    {
      label: "Special cases",
      items: chain(
        [
          () => take("specialNotes", 2),
          () => take("importantStatements", 2),
          () => take("universalFacts", 2),
          () => take("confusion", 2, 380),
        ],
        2,
      ),
    },
    {
      label: "Solved",
      items: chain(
        [() => take("examples", 2, 420), () => take("practice", 2, 380), () => take("practiceQuestions", 1, 380)],
        2,
      ),
    },
    {
      label: "Limitation",
      items: chain(
        [
          () => take("bounds", 2, 300),
          () => take("confusion", 2, 380),
          () => take("importantNotes", 2),
          () => take("specialNotes", 2),
        ],
        2,
      ),
    },
    {
      label: "Derivation",
      items: chain(
        [
          () => take("importantTasks", 2, 320),
          () => take("notes", 2, 420),
          () => take("keyPoints", 2),
          () => take("importantConcepts", 2),
        ],
        2,
      ),
    },
    {
      label: "Shortcut",
      items: chain(
        [
          () => take("examShortTricks", 2, 320),
          () => take("examNotes", 2, 320),
          () => take("universalFacts", 2),
        ],
        2,
      ),
    },
    {
      label: "Board question",
      items: chain(
        [
          () => take("practiceQuestions", 2, 340),
          () => take("examNotes", 2, 320),
          () => mcqText(1),
          () => take("practice", 2, 340),
        ],
        2,
      ),
    },
    {
      // Guaranteed on every card (owner ask: "hints"): the first hint-ish
      // field the record carries, then whatever is left — never omitted.
      label: "Hints",
      items: chain(
        [
          () => take("examNotes", 2, 320),
          () => take("importantNotes", 2, 320),
          () => take("specialNotes", 2, 320),
          () => take("confusion", 2, 340),
          () => take("keyPoints", 2, 320),
          () => take("importantStatements", 2, 320),
          () => take("universalFacts", 2, 320),
        ],
        2,
      ),
    },
  ];

  // No canonical row may end up empty: drain whatever the record still carries
  // (each string used once per card). A record too thin to fill all nine gets
  // last-resort verbatim reuse of its own text — the card still only ever says
  // what the topic record says, and no topic is dropped from its rail.
  const pool = FIELD_ORDER.flatMap((f) => fieldList(f).map((s) => clip(s, 320))).filter(
    (s) => s && !s.startsWith(TODO),
  );
  for (const draft of drafts) {
    if (draft.items.length === 0) draft.items.push(...takeAny(2));
    if (draft.items.length === 0 && pool.length > 0) {
      draft.items.push(pool[drafts.indexOf(draft) % pool.length]);
    }
  }

  // Leftover ideas — "all ideas possible" rows, filled from what the canonical
  // nine did not consume.
  const extras: RowDraft[] = [
    { label: "Quick concepts", items: take("importantConcepts", 4, 320) },
    { label: "Key points", items: take("keyPoints", 4, 320) },
    { label: "Universal facts", items: take("universalFacts", 2, 340) },
    { label: "More practice", items: take("practiceQuestions", 3, 300) },
    { label: "More hints", items: take("examNotes", 2, 320) },
    { label: "Extra solved", items: take("examples", 2, 380) },
    { label: "MCQ drill", items: mcqText(2) },
    { label: "Study notes", items: take("notes", 3, 380) },
  ];

  const rows: HomeRailFileRow[] = [];
  for (const draft of [...drafts, ...extras]) {
    if (draft.items.length === 0) continue;
    rows.push({
      label: draft.label,
      ...(draft.kind ? { kind: draft.kind } : {}),
      text: draft.items.join(draft.kind === "formula" ? "\n" : "  ·  "),
    });
  }

  // "More ideas" drain — the blocks are large, so keep offering whatever the
  // record still carries (each string used at most once per card) until its
  // idea pool runs dry; bounded so no single card grows without limit.
  for (let drained = 0; drained < 5; drained += 1) {
    const items = takeAny(3, 320);
    if (items.length === 0) break;
    rows.push({ label: "More ideas", text: items.join("  ·  ") });
  }

  // Diagram ideas: up to 4 headline concepts/key points (may reuse row slices).
  const mapIdeas = [
    ...fieldList("importantConcepts").slice(0, 2),
    ...fieldList("keyPoints").slice(0, 2),
    ...fieldList("formulas").slice(0, 2),
  ]
    .map((s) => clip(s, 100))
    .slice(0, 4);

  return { rows, mapIdeas };
}

// ─────────────────────────────────────────────────────────────────────────────
// Card assembly
// ─────────────────────────────────────────────────────────────────────────────
interface TopicContext {
  classSlug: string;
  subjectSlug: string;
  unitId: string;
  unitTitle: string;
  unitTopics: string[];
}

/**
 * Prefer the live topic page when the concept's slug is a real syllabus topic
 * slug (the route 404s otherwise); fall back to the unit page, which always
 * ships. `card.href` must never point at a route that does not exist (§9).
 */
function topicHref(ctx: TopicContext, topicSlug: string): string {
  const entries = getUnitTopicEntries({
    id: ctx.unitId,
    title: ctx.unitTitle,
    topics: ctx.unitTopics,
  });
  const hit = entries.some((e) => e.slug === topicSlug);
  return hit
    ? `/${ctx.classSlug}/${ctx.subjectSlug}/chapters/${ctx.unitId}/topics/${topicSlug}`
    : unitHref(ctx);
}

function unitHref(ctx: TopicContext): string {
  return `/${ctx.classSlug}/${ctx.subjectSlug}/${ctx.unitId}`;
}

function buildCard(
  c: ConceptRecord,
  ctx: TopicContext,
  srcFile: string,
  mindmap?: MindmapNode,
): HomeRailFile {
  const title = text(c.title) || text(c.topicTitle) || text(c.topicSlug) || "Untitled topic";
  const topicSlug = text(c.topicSlug) || title.toLowerCase().replace(/[^a-z0-9]+/g, "-");
  const { rows, mapIdeas } = buildRows(c);

  // Diagram 1 — the idea-map drawing on the Concept row (diagram at the idea
  // it explains, per the §9 figure contract).
  let conceptDrawn = false;
  const withFigure = rows.map((row) => {
    if (conceptDrawn || row.label !== "Concept") return row;
    conceptDrawn = true;
    return {
      ...row,
      figure: {
        svg: ideaMapSvg(title, mapIdeas),
        caption: clip(`${title} — quick idea map of this topic's headline ideas`, 150),
      },
    };
  });

  // Diagram 2 — the blocks are large, so every card carries a second drawing:
  // the corpus's own topic mind map where one exists, else a formula board for
  // formula-shaped rows, else the exam-flow ladder of the card's own steps.
  const realFormulas = arr(c.formulas).filter(formulaLooksReal);
  const stepRow = (label: string): { label: string; text: string } => {
    const hit = rows.find((r) => r.label === label);
    return { label, text: clip(hit?.text ?? title, 120) };
  };
  let secondFigure: { svg: string; caption: string };
  let secondTargets: string[];
  if (mindmap && (mindmap.children?.length ?? 0) > 0) {
    secondFigure = {
      svg: mindMapSvg(title, mindmap),
      caption: clip(`${title} — topic mind map of this topic's own sub-topics`, 150),
    };
    secondTargets = ["Quick concepts", "Key points", "Study notes", "Hints"];
  } else if (realFormulas.length > 0) {
    secondFigure = {
      svg: formulaBoardSvg(title, realFormulas),
      caption: clip(`${title} — formula board of this topic's own formulas`, 150),
    };
    secondTargets = ["Formula"];
  } else {
    secondFigure = {
      svg: examFlowSvg(title, [
        stepRow("Concept"),
        stepRow("Formula"),
        stepRow("Shortcut"),
        stepRow("Board question"),
      ]),
      caption: clip(`${title} — exam flow: concept → formula → shortcut → board question`, 150),
    };
    secondTargets = ["Board question", "Hints", "More practice"];
  }
  let secondDrawn = false;
  const withBoth = withFigure.map((row) => {
    if (secondDrawn || row.figure || !secondTargets.includes(row.label)) return row;
    secondDrawn = true;
    return { ...row, figure: secondFigure };
  });
  // Thin records may skip every target label — the drawing then lands on the
  // first row without one, so no card is left with a single diagram.
  if (!secondDrawn) {
    for (let i = 0; i < withBoth.length; i += 1) {
      if (withBoth[i].figure) continue;
      withBoth[i] = { ...withBoth[i], figure: secondFigure };
      break;
    }
  }
  const finalRows = withBoth;

  return {
    schema: HOME_RAIL_SCHEMA,
    draft: false,
    classSlug: ctx.classSlug,
    subjectSlug: ctx.subjectSlug,
    unitSlug: ctx.unitId,
    unitTitle: ctx.unitTitle,
    syllabusTopics: ctx.unitTopics.slice(0, 12),
    source: "platform",
    agentNotes: `${GENERATED_BY} from ${srcFile} (verbatim slices of that topic's concept record; idea-map diagram generated from its own headline ideas).`,
    card: {
      tag: clip(title, 42),
      title,
      href: topicHref(ctx, topicSlug),
      icon: HOME_RAIL_SUBJECT_ICONS[ctx.subjectSlug] ?? "BookOpen",
      statKey: `pyq:${ctx.subjectSlug}`,
    },
    rows: finalRows,
  };
}

/** Readiness mirror of railReadiness + figure guard, for the report. */
function cardProblems(record: HomeRailFile): string[] {
  const problems = [...checkRailShape(record), ...railReadiness(record)];
  record.rows.forEach((row, i) => {
    if (!row.figure) return;
    if (typeof row.figure.svg !== "string" || !row.figure.svg.trim()) {
      problems.push(`rows[${i}].figure.svg empty`);
      return;
    }
    if (!/^<svg[\s>]/i.test(row.figure.svg.trim()) || !/<\/svg>\s*$/i.test(row.figure.svg.trim())) {
      problems.push(`rows[${i}].figure.svg is not one complete <svg>…</svg> block`);
    }
    if (row.figure.svg.split("<").length - 1 > 900) problems.push(`rows[${i}].figure too many elements`);
  });
  return problems;
}

// ─────────────────────────────────────────────────────────────────────────────
// Walk the corpus
// ─────────────────────────────────────────────────────────────────────────────
interface TopicFile {
  /** Unit content dir holding this topic's `concepts/` (and maybe `mindmap/`). */
  dir: string;
  file: string;
  record: ConceptRecord;
}

/** All concept dirs that feed one syllabus unit (exact dir + legacy aliases). */
function conceptDirsFor(corpusRoot: string, classSlug: string, subjectSlug: string, unitId: string): string[] {
  const subjectDir = path.join(
    corpusRoot,
    "content",
    "notes",
    "concepts",
    classDirOfTrack(classSlug),
    subjectSlug,
  );
  const dirs: string[] = [];
  const resolved = resolveUnitSectionDir(corpusRoot, classSlug, subjectSlug, unitId);
  if (fs.existsSync(resolved)) dirs.push(resolved);
  if (fs.existsSync(subjectDir)) {
    for (const entry of fs.readdirSync(subjectDir, { withFileTypes: true })) {
      if (!entry.isDirectory()) continue;
      const abs = path.join(subjectDir, entry.name);
      if (dirs.includes(abs)) continue;
      if (entry.name === unitId || LEGACY_UNIT_INDEX[entry.name] === unitId) dirs.push(abs);
    }
  }
  return dirs;
}

/** The unit's mindmap dir in the classified tree, derived from its concept dir. */
function mindmapDirFor(conceptDir: string): string {
  return conceptDir.replace(
    `${path.sep}notes${path.sep}concepts${path.sep}`,
    `${path.sep}visuals${path.sep}mindmaps${path.sep}`,
  );
}

/**
 * The corpus's own per-topic mind maps (`mindmap/*.json`), keyed by topicSlug.
 * Mind-map file names carry a `NN-` prefix and don't match concept file names,
 * so the index is built from each map's own `topicSlug` field. Unit-level maps
 * (`mindmap.json`, `_unit-*.json`) are not topic maps and are skipped.
 */
function readMindmapIndex(dirs: string[]): Map<string, MindmapNode> {
  const out = new Map<string, MindmapNode>();
  for (const dir of dirs) {
    const mindmapDir = mindmapDirFor(dir);
    if (!fs.existsSync(mindmapDir)) continue;
    for (const f of fs.readdirSync(mindmapDir)) {
      if (!f.endsWith(".json") || f === "mindmap.json" || f.startsWith("_unit-")) continue;
      try {
        const parsed = JSON.parse(fs.readFileSync(path.join(mindmapDir, f), "utf8")) as {
          topicSlug?: unknown;
          root?: MindmapNode;
        };
        const slug = text(parsed.topicSlug) || f.replace(/\.json$/, "");
        if (parsed.root && typeof parsed.root === "object" && !out.has(slug)) {
          out.set(slug, parsed.root);
        }
      } catch {
        // An unreadable mind map just means this topic gets a different diagram.
      }
    }
  }
  return out;
}

function readTopics(dir: string): TopicFile[] {
  // `dir` IS the concepts dir in the classified tree.
  const conceptsDir = dir;
  if (!fs.existsSync(conceptsDir)) return [];
  return fs
    .readdirSync(conceptsDir)
    .filter((f) => f.endsWith(".json"))
    .sort((a, b) => a.localeCompare(b))
    .map((f) => {
      try {
        return {
          dir,
          file: f,
          record: JSON.parse(fs.readFileSync(path.join(conceptsDir, f), "utf8")) as ConceptRecord,
        };
      } catch {
        return null;
      }
    })
    .filter((t): t is TopicFile => t !== null);
}

/** One topic per topicSlug: keep the primary (lowest duplicateType), then name. */
function dedupe(topics: TopicFile[]): TopicFile[] {
  const bySlug = new Map<string, TopicFile>();
  for (const t of topics) {
    const slug = text(t.record.topicSlug) || t.file.replace(/\.json$/, "");
    const rank = Number(t.record.duplicateType ?? 1) || 1;
    const prev = bySlug.get(slug);
    if (!prev) {
      bySlug.set(slug, t);
      continue;
    }
    const prevRank = Number(prev.record.duplicateType ?? 1) || 1;
    if (rank < prevRank || (rank === prevRank && t.file.localeCompare(prev.file) < 0)) {
      bySlug.set(slug, t);
    }
  }
  return [...bySlug.entries()].sort((a, b) => a[0].localeCompare(b[0])).map(([, t]) => t);
}

function numPrefix(fileName: string): string {
  const m = /^(\d{1,3})-/.exec(fileName);
  return m ? m[1].padStart(2, "0") : "00";
}

/**
 * File-name-safe topic slug, capped at 48 chars. Windows paths top out near
 * 260 characters and some syllabus topics slug to 200+ characters, which broke
 * `--write` mid-run (ENOENT). The CARD keeps the full title and rows — only
 * the file name is shortened, and a 6-char content hash keeps it unique.
 */
function fileSlug(slug: string): string {
  const safe = slug
    .toLowerCase()
    .replace(/[^a-z0-9\u0900-\u097f-]+/g, "-")
    .replace(/^-+|-+$/g, "");
  if (safe.length <= 48) return safe || "topic";
  let hash = 0;
  for (let i = 0; i < safe.length; i += 1) {
    hash = (hash * 31 + safe.charCodeAt(i)) >>> 0;
  }
  return `${safe.slice(0, 40)}-${hash.toString(36).slice(0, 6)}`;
}

function main(): void {
  const corpusRoot = findCorpusRoot();
  let written = 0;
  let skippedExisting = 0;
  let notReady = 0;
  let stale = 0;
  let problems = 0;
  const perSubject: Record<string, number> = {};
  const problemLines: string[] = [];

  for (const classSlug of HOME_RAIL_CLASS_SLUGS) {
    if (CLASS_FILTER && classSlug !== CLASS_FILTER) continue;
    for (const subject of homeRailSubjects(classSlug)) {
      if (SUBJECT_FILTER && subject.slug !== SUBJECT_FILTER) continue;
      for (const unit of subject.units) {
        if (UNIT_FILTER && unit.id !== UNIT_FILTER) continue;
        const dirs = conceptDirsFor(corpusRoot, classSlug, subject.slug, unit.id);
        if (dirs.length === 0) continue;

        const topics = dedupe(dirs.flatMap((d) => readTopics(d)));
        const railsDir = resolveUnitSectionDir(
          corpusRoot,
          classSlug,
          subject.slug,
          unit.id,
          "visuals/rails",
        );
        const mindmaps = readMindmapIndex(dirs);
        const ctx: TopicContext = {
          classSlug,
          subjectSlug: subject.slug,
          unitId: unit.id,
          unitTitle: unit.title,
          unitTopics: unit.topics,
        };
        /** Every card name this unit's topics legitimately produce. */
        const expectedNames = new Set<string>();

        for (const topic of topics) {
          const slug = text(topic.record.topicSlug) || topic.file.replace(/\.json$/, "");
          const name = `${unit.id}--${numPrefix(topic.file)}-${fileSlug(slug)}${RAIL_FILE_SUFFIX}`;
          expectedNames.add(name);
          const outPath = path.join(railsDir, name);
          const rel = path.relative(corpusRoot, outPath).replaceAll(path.sep, "/");

          const record = buildCard(
            flatten(topic.record),
            ctx,
            `concepts/${topic.file}`,
            mindmaps.get(slug),
          );
          const cardIssues = cardProblems(record);
          if (cardIssues.length > 0) {
            notReady += 1;
            problemLines.push(`[not-ready] ${rel}: ${cardIssues.slice(0, 2).join("; ")}`);
            continue;
          }

          const serialized = `${JSON.stringify(record, null, 2)}\n`;

          if (WRITE) {
            if (fs.existsSync(outPath)) {
              const existing = fs.readFileSync(outPath, "utf8");
              if (!existing.includes(GENERATED_BY)) {
                skippedExisting += 1;
                problemLines.push(`[kept-handwritten] ${rel}`);
                continue;
              }
            }
            fs.mkdirSync(railsDir, { recursive: true });
            fs.writeFileSync(outPath, serialized, "utf8");
            written += 1;
            perSubject[subject.slug] = (perSubject[subject.slug] ?? 0) + 1;
          } else if (CHECK) {
            if (!fs.existsSync(outPath)) {
              problems += 1;
              problemLines.push(`[missing] ${rel}`);
            } else {
              const onDisk = fs.readFileSync(outPath, "utf8");
              if (!onDisk.includes(GENERATED_BY)) {
                skippedExisting += 1;
              } else if (onDisk !== serialized) {
                problems += 1;
                problemLines.push(`[drift] ${rel} differs from regenerated card`);
              } else {
                perSubject[subject.slug] = (perSubject[subject.slug] ?? 0) + 1;
              }
            }
          } else {
            perSubject[subject.slug] = (perSubject[subject.slug] ?? 0) + 1;
          }
        }

        // Stale-card sweep — a card this generator wrote under an older name
        // (pre-cap filename, renamed topic) would otherwise linger as a
        // duplicate on the rail. Only files with this script's own GENERATED_BY
        // marker are touched: hand-written cards, the canonical unit card and
        // other generators' output (e.g. `--old-is-gold`) are never deleted.
        if (fs.existsSync(railsDir)) {
          for (const file of fs.readdirSync(railsDir)) {
            if (!file.endsWith(RAIL_FILE_SUFFIX) || expectedNames.has(file)) continue;
            const stalePath = path.join(railsDir, file);
            const body = fs.readFileSync(stalePath, "utf8");
            if (!body.includes(GENERATED_BY)) continue;
            const staleRel = path.relative(corpusRoot, stalePath).replaceAll(path.sep, "/");
            if (WRITE) {
              fs.unlinkSync(stalePath);
              stale += 1;
              problemLines.push(`[swept-stale] ${staleRel}`);
            } else if (CHECK) {
              problems += 1;
              problemLines.push(`[stale] ${staleRel} is not a name any current topic produces`);
            }
          }
        }
      }
    }
  }

  if (!QUIET) {
    console.log(`topic-rails ${WRITE ? "--write" : CHECK ? "--check" : "dry-run"} (${corpusRoot})`);
    for (const [subject, count] of Object.entries(perSubject)) {
      console.log(`  ${subject.padEnd(12)} ${count} topic cards`);
    }
    console.log(
      `  total: ${Object.values(perSubject).reduce((a, b) => a + b, 0)}` +
        (written ? ` written: ${written}` : "") +
        (skippedExisting ? ` kept-existing: ${skippedExisting}` : "") +
        (notReady ? ` not-ready: ${notReady}` : "") +
        (stale ? ` swept-stale: ${stale}` : "") +
        (problems ? ` problems: ${problems}` : ""),
    );
    for (const line of problemLines.slice(0, 30)) console.log(`  ${line}`);
  }

  if (CHECK && problems > 0) {
    console.error(`topic-rails --check FAILED: ${problems} problem(s)`);
    process.exit(1);
  }
}

main();
