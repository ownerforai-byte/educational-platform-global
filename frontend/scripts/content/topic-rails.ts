/**
 * Flatten nested content blocks (enrichedContent / originalContent) into one
 * record view — same field names, so rows stay verbatim slices either way.
 * Top-level fields win; nested lists only append strings the top level lacks.
 */
function flatten(c: ConceptRecord): ConceptRecord {
  const out: ConceptRecord = { ...c };
  for (const block of [c.enrichedContent, c.originalContent]) {
    if (!block || typeof block !== "object") continue;
    for (const key of FIELD_ORDER) {
      const top = out[key];
      const nested = (block as Record<string, unknown>)[key as string];
      if (Array.isArray(top) || typeof top === "string") continue;
      if (Array.isArray(nested) || typeof nested === "string") {
        (out as Record<string, unknown>)[key as string] = nested;
      }
    }
  }
  return out;
}

/** Clip a verbatim slice at a sentence (or word) boundary — never mid-word. */
function clip(text: string, max: number): string {
  const clean = text.replace(/\s+/g, " ").trim();
  if (clean.length <= max) return clean;
  const cut = clean.slice(0, max);
  const sentence = cut.lastIndexOf(". ");
  if (sentence > max * 0.55) return `${cut.slice(0, sentence + 1)}…`;
  const word = cut.lastIndexOf(" ");
  return `${cut.slice(0, word > 0 ? word : max)}…`;
}

function arr(value: unknown): string[] {
  return Array.isArray(value) ? value.filter((v) => typeof v === "string") : [];
}

function text(value: unknown): string {
  return typeof value === "string" ? value.trim() : "";
}

// ─────────────────────────────────────────────────────────────────────────────
// Idea map diagram — deterministic, guard-safe (no id/defs/style/script/url)
// ─────────────────────────────────────────────────────────────────────────────
function xmlEscape(value: string): string {
  return value
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

function wrap(value: string, perLine: number, lines: number): string[] {
  const words = xmlEscape(clip(value, perLine * lines)).split(" ");
  const out: string[] = [];
  let line = "";
  for (const w of words) {
    if (!line) line = w;
    else if (`${line} ${w}`.length <= perLine) line = `${line} ${w}`;
    else {
      out.push(line);
      line = w;
      if (out.length === lines) break;
    }
  }
  if (line && out.length < lines) out.push(line);
  return out;
}

/** A labelled idea-map drawing: topic title → up to 4 idea boxes. */
function ideaMapSvg(topicTitle: string, ideas: string[]): string {
  const boxes = ideas.slice(0, 4).map((idea) => wrap(idea, 26, 3));
  const titleLines = wrap(topicTitle, 46, 2);
  const parts: string[] = [];
  parts.push(
    `<svg viewBox="0 0 900 640" role="img" aria-label="${xmlEscape(clip(topicTitle, 120))} — quick idea map">`,
  );
  parts.push(`<title>${xmlEscape(clip(topicTitle, 120))} — quick idea map</title>`);
  // Title banner
  parts.push(
    `<rect x="180" y="24" width="540" height="86" rx="10" fill="#e0f2fe" stroke="#0369a1" stroke-width="3"/>`,
  );
  titleLines.forEach((line, i) => {
    parts.push(
      `<text x="450" y="${58 + i * 30}" text-anchor="middle" font-size="23" font-weight="bold" fill="#0c4a6e">${line}</text>`,
    );
  });
  // 2×2 idea grid with arrows from the banner
  const cols = [70, 490];
  const rowsY = [190, 400];
  let box = 0;
  for (const y of rowsY) {
    for (const x of cols) {
      if (box >= boxes.length) break;
      const cx = x + 170;
      // connector: line + polygon arrowhead
      const fromY = 110;
      parts.push(
        `<line x1="450" y1="${fromY}" x2="${cx}" y2="${y - 8}" stroke="#0284c7" stroke-width="2.5" stroke-linecap="round"/>`,
      );
      parts.push(
        `<polygon points="${cx - 7},${y - 18} ${cx + 7},${y - 18} ${cx},${y - 4}" fill="#0284c7"/>`,
      );
      parts.push(
        `<rect x="${x}" y="${y}" width="340" height="140" rx="10" fill="#f0f9ff" stroke="#0284c7" stroke-width="2.5"/>`,
      );
      boxes[box].forEach((line, li) => {
        parts.push(
          `<text x="${x + 170}" y="${y + 38 + li * 32}" text-anchor="middle" font-size="21" fill="#0c4a6e">${line}</text>`,
        );
      });
      box += 1;
    }
  }
  if (boxes.length === 0) {
    parts.push(
      `<text x="450" y="300" text-anchor="middle" font-size="22" fill="#64748b">Idea map — see rows below</text>`,
    );
  }
  parts.push(`</svg>`);
  return parts.join("");
}

/** A node of the corpus's own per-topic mind map (`mindmap/<topic>.json`). */
interface MindmapNode {
  label?: string;
  children?: MindmapNode[];
}

/**
 * Topic mind map — the corpus's own tree, drawn as root banner → up to 4 idea
 * branches → their sub-topic lines. Same primitives as the idea map (rect,
 * line, polygon, text) so the note-visuals guard always passes it.
 */
function mindMapSvg(topicTitle: string, root: MindmapNode): string {
  const branches = (Array.isArray(root.children) ? root.children : []).slice(0, 4);
  const titleLines = wrap(text(root.label) || topicTitle, 46, 2);
  const parts: string[] = [];
  const aria = clip(`${topicTitle} — topic mind map`, 120);
  parts.push(`<svg viewBox="0 0 900 640" role="img" aria-label="${xmlEscape(aria)}">`);
  parts.push(`<title>${xmlEscape(aria)}</title>`);
  parts.push(
    `<rect x="180" y="24" width="540" height="86" rx="10" fill="#ede9fe" stroke="#6d28d9" stroke-width="3"/>`,
  );
  titleLines.forEach((line, i) => {
    parts.push(
      `<text x="450" y="${58 + i * 30}" text-anchor="middle" font-size="23" font-weight="bold" fill="#4c1d95">${line}</text>`,
    );
  });
  const cols = [70, 490];
  const rowsY = [190, 400];
  let box = 0;
  for (const y of rowsY) {
    for (const x of cols) {
      if (box >= branches.length) break;
      const branch = branches[box];
      const cx = x + 170;
      parts.push(
        `<line x1="450" y1="110" x2="${cx}" y2="${y - 8}" stroke="#7c3aed" stroke-width="2.5" stroke-linecap="round"/>`,
      );
      parts.push(
        `<polygon points="${cx - 7},${y - 18} ${cx + 7},${y - 18} ${cx},${y - 4}" fill="#7c3aed"/>`,
      );
      parts.push(
        `<rect x="${x}" y="${y}" width="340" height="140" rx="10" fill="#f5f3ff" stroke="#7c3aed" stroke-width="2.5"/>`,
      );
      wrap(text(branch.label) || "Sub-topic", 24, 2).forEach((line, li) => {
        parts.push(
          `<text x="${x + 170}" y="${y + 34 + li * 28}" text-anchor="middle" font-size="20" font-weight="bold" fill="#4c1d95">${line}</text>`,
        );
      });
      (Array.isArray(branch.children) ? branch.children : [])
        .slice(0, 2)
        .forEach((leaf, li) => {
          const line = wrap(text(leaf.label), 30, 1)[0];
          if (!line) return;
          parts.push(
            `<text x="${x + 170}" y="${y + 100 + li * 26}" text-anchor="middle" font-size="17" fill="#5b21b6">${line}</text>`,
          );
        });
      box += 1;
    }
  }
  if (branches.length === 0) {
    parts.push(
      `<text x="450" y="300" text-anchor="middle" font-size="22" fill="#6d28d9">${xmlEscape(clip(topicTitle, 60))}</text>`,
    );
  }
  parts.push(`</svg>`);
  return parts.join("");
}

