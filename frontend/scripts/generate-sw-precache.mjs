#!/usr/bin/env node
/**
 * generate-sw-precache — build the service worker's route list from the app
 * router tree instead of a hand-written list that goes stale on every page
 * addition.
 *
 *   node scripts/generate-sw-precache.mjs           # write public/sw-precache.json
 *   node scripts/generate-sw-precache.mjs --check   # CI gate: fail on drift
 *
 * Only STATIC routes are precached: dynamic segments ([slug]) have no single
 * URL to cache. The core shell routes are always kept first, then the rest of
 * the static tree up to a bounded cap so a low-data device never pays for a
 * huge install. The generated file is committed: sw.js falls back to its
 * built-in SW_ROUTES list when the file is unavailable (e.g. plain `next dev`).
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const APP = path.join(ROOT, "app");
const OUT = path.join(ROOT, "public", "sw-precache.json");
const CHECK = process.argv.includes("--check");
const MAX_ROUTES = 40;

/** The app shell must always be available offline, even if the tree changes. */
const CORE = [
  "/",
  "/home",
  "/offline",
  "/downloads",
  "/chat",
  "/notes",
  "/lab",
  "/quiz",
  "/subjects",
  "/syllabus",
  "/progress",
  "/bookmarks",
];

/** Student-facing destinations that deserve a slot before an alphabetical fill. */
const PREFERRED = [
  "/help",
  "/plans",
  "/contact",
  "/pyqs",
  "/formulas",
  "/practice",
  "/exams",
  "/my-notes",
  "/analytics",
  "/goals",
  "/schedule",
  "/revision",
  "/leaderboard",
  "/community",
  "/ai-quiz",
  "/class-11-notes",
  "/class-12-notes",
  "/legal/privacy",
  "/legal/terms",
  "/legal/takedown",
  "/legal/attribution",
];

/** Owner/error surfaces must not be prefetched on a student's device. */
function excluded(route) {
  return (
    /^\/(4\d\d|5\d\d|network)$/.test(route) ||
    /^\/(admin|owner|controller|mind-studio|ad-p-table)(\/|$)/.test(route)
  );
}

function walk(dir, acc = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(full, acc);
    else if (entry.name === "page.tsx" || entry.name === "page.ts") acc.push(full);
  }
  return acc;
}

function routeFor(file) {
  const rel = path.relative(APP, file).replace(/\\/g, "/");
  const segments = rel.split("/").slice(0, -1);
  if (segments.some((s) => s.startsWith("[") || s === "api")) return null;
  // Route groups such as (app) are URL-transparent.
  const url = "/" + segments.filter((s) => !/^\(.*\)$/.test(s)).join("/");
  return url === "/" ? "/" : url.replace(/\/$/, "");
}

const discovered = new Set();
for (const file of walk(APP)) {
  const route = routeFor(file);
  if (route) discovered.add(route);
}

const available = [...discovered].filter((r) => !excluded(r));
const preferred = PREFERRED.filter((r) => available.includes(r));
const chosen = new Set([...CORE, ...preferred]);
const rest = available
  .filter((r) => !chosen.has(r))
  .sort((a, b) => a.split("/").length - b.split("/").length || a.localeCompare(b))
  .slice(0, Math.max(0, MAX_ROUTES - chosen.size));

const payload = {
  note: "Generated by scripts/generate-sw-precache.mjs from frontend/app/**/page.tsx. Regenerate after adding a static route.",
  generatedAt: new Date().toISOString().slice(0, 10),
  routes: [...chosen, ...rest],
};

if (CHECK) {
  let existing = null;
  try {
    existing = JSON.parse(fs.readFileSync(OUT, "utf8"));
  } catch {
    console.error("sw-precache: missing or invalid public/sw-precache.json — run the generator.");
    process.exit(1);
  }
  const same =
    JSON.stringify(existing.routes) === JSON.stringify(payload.routes);
  if (!same) {
    console.error("sw-precache: DRIFT — the app router tree changed.");
    console.error(`  committed: ${existing.routes?.length ?? 0} routes`);
    console.error(`  generated: ${payload.routes.length} routes`);
    console.error("Run `npm run sw:precache` in frontend and commit the result.");
    process.exit(1);
  }
  console.log(`sw-precache: GATE PASS — ${payload.routes.length} routes in sync with the app tree.`);
  process.exit(0);
}

fs.writeFileSync(OUT, JSON.stringify(payload, null, 2) + "\n", "utf8");
console.log(`sw-precache: wrote ${payload.routes.length} routes to public/sw-precache.json`);
