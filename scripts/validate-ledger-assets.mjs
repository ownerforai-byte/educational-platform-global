#!/usr/bin/env node
/**
 * validate-ledger-assets.mjs — structural schema gate for the shipped content
 * ledger (`frontend/public/data/content-ledger.json`).
 *
 * The ledger is the registry every topic page, "notes" pill and AI tutor
 * trusts. JSON that parses cleanly but has a missing field, a malformed
 * sha256, or roll-up totals that drifted is worse than no ledger: pages keep
 * promising notes that do not exist. This gate validates the shape AND
 * recomputes every roll-up total from the leaf entries, so drift becomes a CI
 * failure instead of a live 404.
 *
 * Exits 0 on a clean ledger, 1 with a per-problem report otherwise.
 *
 * Declared payload files that are absent are WARNINGS, not failures. The
 * public `content/_index.json` was retired by 7bb51358 (paid bodies moved off
 * the public CDN) and is no longer a ledger source; the remaining generated
 * assets are tracked again after f6419cf broke `ledger:check` by untracking
 * them. A warning keeps any future disappearance visible in the Actions log
 * instead of silently weakening the gate.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const LEDGER_PATH = path.join(REPO, "frontend", "public", "data", "content-ledger.json");

const problems = [];
const fail = (message) => {
  problems.push(message);
  console.error(`  FAIL  ${message}`);
};
const warn = (message) => console.log(`::warning::${message}`);
const isObject = (value) =>
  value !== null && typeof value === "object" && !Array.isArray(value);
const isCount = (value) => Number.isInteger(value) && value >= 0;
const SHA256 = /^[a-f0-9]{64}$/;
const num = (value) => (isCount(value) ? value : 0);

function expectObject(value, label) {
  if (!isObject(value)) {
    fail(`${label}: expected an object`);
    return false;
  }
  return true;
}

function expectCounts(value, label, keys = ["entries", "authored", "template", "bytes"]) {
  if (!expectObject(value, label)) return;
  for (const key of keys) {
    if (!isCount(value[key])) fail(`${label}.${key}: expected a non-negative integer`);
  }
  if (isCount(value.authored) && isCount(value.template) && isCount(value.entries)) {
    if (value.authored + value.template > value.entries) {
      fail(`${label}: authored + template exceeds entries`);
    }
  }
  if (isCount(value.authored) && isCount(value.template) && isCount(value.claims)) {
    if (value.authored + value.template > value.claims) {
      fail(`${label}: authored + template exceeds claims`);
    }
  }
}

function expectSha(value, label) {
  if (typeof value !== "string" || !SHA256.test(value)) {
    fail(`${label}: expected a 64-character hex sha256`);
  }
}

function expectEqual(declared, actual, label) {
  if (isCount(declared) && declared !== actual) {
    fail(`${label}: declared ${declared} != recomputed ${actual}`);
  }
}

function warnIfGenerated(source, label) {
  if (typeof source !== "string" || !source) return;
  if (!fs.existsSync(path.join(REPO, source))) {
    warn(
      `${label}: ${source} is not tracked (generated by \`npm run content:build\` at release time)`,
    );
  }
}

console.log(`ledger: ${path.relative(REPO, LEDGER_PATH)}`);

let ledger;
try {
  ledger = JSON.parse(fs.readFileSync(LEDGER_PATH, "utf8"));
} catch (error) {
  console.error(`  FAIL  cannot parse ledger: ${error.message}`);
  process.exit(1);
}

for (const key of [
  "scope",
  "source",
  "legend",
  "totals",
  "subjects",
  "orphans",
  "supplementary",
  "sources",
]) {
  if (!(key in ledger)) fail(`ledger: missing top-level key "${key}"`);
}
if (typeof ledger.scope !== "string" || !ledger.scope.trim()) {
  fail("ledger.scope: expected a non-empty string");
}
if (typeof ledger.source !== "string" || !ledger.source.trim()) {
  fail("ledger.source: expected a non-empty string");
}
expectObject(ledger.legend, "ledger.legend");
expectCounts(ledger.totals, "ledger.totals");

// Recompute every roll-up total from the leaf entries.
const rollup = { entries: 0, authored: 0, template: 0, bytes: 0 };
if (expectObject(ledger.subjects, "ledger.subjects")) {
  for (const [subject, node] of Object.entries(ledger.subjects)) {
    const subjectLabel = `ledger.subjects.${subject}`;
    if (!expectObject(node, subjectLabel)) continue;
    expectCounts(node.totals, `${subjectLabel}.totals`);
    if (!expectObject(node.units, `${subjectLabel}.units`)) continue;

    const subjectTotals = { entries: 0, authored: 0, template: 0, bytes: 0 };
    for (const [unit, group] of Object.entries(node.units)) {
      const label = `${subjectLabel}.units.${unit}`;
      if (!expectObject(group, label)) continue;
      expectCounts(group.totals, `${label}.totals`);
      if (!Array.isArray(group.entries)) {
        fail(`${label}.entries: expected an array`);
        continue;
      }

      const unitTotals = { entries: 0, authored: 0, template: 0, bytes: 0 };
      group.entries.forEach((entry, index) => {
        const at = `${label}.entries[${index}]`;
        if (!isObject(entry)) {
          fail(`${at}: expected an object`);
          return;
        }
        if (typeof entry.topicSlug !== "string" || !entry.topicSlug) {
          fail(`${at}.topicSlug: expected a non-empty string`);
        }
        if (typeof entry.filename !== "string" || !entry.filename) {
          fail(`${at}.filename: expected a non-empty string`);
        }
        if (!isCount(entry.bytes)) fail(`${at}.bytes: expected a non-negative integer`);
        expectSha(entry.sha256, `${at}.sha256`);
        if (entry.status !== "authored" && entry.status !== "template") {
          fail(`${at}.status: expected authored|template`);
        }
        unitTotals.entries += 1;
        unitTotals.bytes += num(entry.bytes);
        if (entry.status === "authored") unitTotals.authored += 1;
        else if (entry.status === "template") unitTotals.template += 1;
      });

      for (const key of Object.keys(unitTotals)) {
        expectEqual(group.totals?.[key], unitTotals[key], `${label}.totals.${key}`);
        subjectTotals[key] += unitTotals[key];
      }
    }
    for (const key of Object.keys(subjectTotals)) {
      expectEqual(node.totals?.[key], subjectTotals[key], `${subjectLabel}.totals.${key}`);
      rollup[key] += subjectTotals[key];
    }
  }
}
for (const key of Object.keys(rollup)) {
  expectEqual(ledger.totals?.[key], rollup[key], `ledger.totals.${key}`);
}

// Every declared data source carries a byte count, a digest and a claim count.
if (Array.isArray(ledger.sources)) {
  ledger.sources.forEach((source, index) => {
    const label = `ledger.sources[${index}]`;
    if (!isObject(source)) {
      fail(`${label}: expected an object`);
      return;
    }
    if (typeof source.path !== "string" || !source.path.startsWith("frontend/")) {
      fail(`${label}.path: expected a repo-relative frontend/ path`);
    }
    if (!isCount(source.bytes)) fail(`${label}.bytes: expected a non-negative integer`);
    if (!isCount(source.claims)) fail(`${label}.claims: expected a non-negative integer`);
    expectSha(source.sha256, `${label}.sha256`);
    warnIfGenerated(source.path, label);
  });
} else {
  fail("ledger.sources: expected an array");
}

const supplementary = ledger.supplementary;
if (expectObject(supplementary, "ledger.supplementary")) {
  if (typeof supplementary.source !== "string" || !supplementary.source) {
    fail("ledger.supplementary.source: expected a non-empty string");
  }
  if (!isCount(supplementary.bytes)) {
    fail("ledger.supplementary.bytes: expected a non-negative integer");
  }
  expectSha(supplementary.sha256, "ledger.supplementary.sha256");
  expectCounts(supplementary.totals, "ledger.supplementary.totals", [
    "claims",
    "authored",
    "template",
  ]);
  expectObject(supplementary.groups, "ledger.supplementary.groups");
  warnIfGenerated(supplementary.source, "ledger.supplementary");
}

if (expectObject(ledger.orphans, "ledger.orphans")) {
  expectCounts(ledger.orphans.totals, "ledger.orphans.totals");
  expectObject(ledger.orphans.subjects, "ledger.orphans.subjects");
}

if (problems.length) {
  console.error(`\nledger schema: FAILED — ${problems.length} problem(s)`);
  process.exit(1);
}
console.log(
  `ledger schema: PASS — ${rollup.entries} entries, ${rollup.authored} authored, ` +
    `${rollup.template} template, ${rollup.bytes} bytes, ${ledger.sources.length} sources`,
);
