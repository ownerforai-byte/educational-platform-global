/**
 * Weekly planner state (/planner) — mirrors `PlannerView`
 * (`frontend/components/study/planner-view.tsx`): the week is generated by
 * the golden-tested `buildWeeklyPlan` from the device goals + the student's
 * weak topics (journey progress) + the injected syllabus catalog.
 *
 * Journey progress comes from [JourneySource]; until Wave 3's progress
 * endpoints land the production binding reports Unavailable and the planner
 * shows the same "no weak topics suggested" line the website shows when the
 * progress API fails — no invented topics.
 */
data class PlannerUiState(
    /** Device goals record — null before the read (website "ready" gate). */
    val goals: StudyGoals? = null,
    val catalog: List<GoalSubject> = emptyList(),
    val days: List<PlanDay> = emptyList(),
    val journeyFailed: Boolean = false,
    val journeyLoading: Boolean = false,
    val today: LocalDate = LocalDate.now(),
) {
    /** Website gate: `ready && goals.subjects.length === 0` → "Needs your study goals". */
    val needsGoals: Boolean get() = goals != null && goals.subjects.isEmpty()

    /** `ready && days.length === 0` → exam date passed. */
    val examPassed: Boolean get() = goals != null && days.isEmpty() && !needsGoals
}

@HiltViewModel
class PlannerViewModel @Inject constructor(
    private val store: GoalsStore,
    private val syllabus: SyllabusRepository,
    private val journey: JourneySource,
) : ViewModel() {

    internal var scope: CoroutineScope = viewModelScope

    constructor(
        store: GoalsStore,
        syllabus: SyllabusRepository,
        journey: JourneySource,
        scope: CoroutineScope,
    ) : this(store, syllabus, journey) {
        this.scope = scope
    }

    private val _state = MutableStateFlow(PlannerUiState())
    val state: StateFlow<PlannerUiState> = _state.asStateFlow()

    init {
        rebuild(today = LocalDate.now())
    }

    /** Full recompute: goals + catalog + journey, then the plan generator. */
    fun rebuild(today: LocalDate) {
        _state.value = _state.value.copy(today = today)
        scope.launch {
            val rawGoals = store.readRaw()

            // Catalog for subject names and subject validation. Load it before
            // normalization so previously selected subject keys are preserved.
            val catalog = loadCatalog()
            val goals = decodeGoals(rawGoals, catalog)
            _state.value = _state.value.copy(goals = goals)
            // Journey weak topics (best-effort — unavailable is honest).
            _state.value = _state.value.copy(journeyLoading = true)
            val journeyResult = runCatching { journey.load() }.getOrNull()
            val entries = when (journeyResult) {
                is JourneySource.Result.Fresh -> journeyResult.entries
                is JourneySource.Result.Cached -> journeyResult.entries
                else -> {
                    _state.value = _state.value.copy(journeyFailed = true, journeyLoading = false)
                    emptyList()
                }
            }
            val weak = weakTopicsFromJourney(entries)
            val days = if (goals.subjects.isEmpty()) {
                emptyList()
            } else {
                buildWeeklyPlan(goals, weak, today, catalog)
            }
            _state.value = _state.value.copy(
                catalog = catalog,
                days = days,
                journeyLoading = false,
            )
        }
    }

    private suspend fun loadCatalog(): List<GoalSubject> {
        val result = runCatching { syllabus.load() }.getOrNull() ?: return emptyList()
        return when (result) {
            is SyllabusRepository.Result.Fresh ->
                (result.payload as? SyllabusRepository.Payload.SyllabusTree)
                    ?.let { goalSubjectsFrom(it.classes) } ?: emptyList()
            is SyllabusRepository.Result.Cached ->
                (result.payload as? SyllabusRepository.Payload.SyllabusTree)
                    ?.let { goalSubjectsFrom(it.classes) } ?: emptyList()
            is SyllabusRepository.Result.Unavailable -> emptyList()
        }
    }
}
