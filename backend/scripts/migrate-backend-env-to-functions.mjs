#!/usr/bin/env node
/**
 * Migrate the backend's local env file to the Firebase Cloud Functions
 * env file for the `api` function (Task A — backend → Cloud Functions).
 *
 *   node scripts/migrate-backend-env-to-functions.mjs [--source <path>] [--out <path>] [--dry-run]
 *
 * Reads backend/.env (dotenv format) and writes firebase/functions-api/
 * .env.rn01-af00b with the runtime-needed variable NAMES + values, mirroring
 * the firebase/functions/.env.rn01-af00b pattern. The output file is
 * gitignored (root .gitignore `.env.*` and firebase/functions-api/.gitignore)
 * — only this script is committed.
 *
 * SECURITY: this script NEVER prints, echoes, or logs variable VALUES — the
 * summary reports variable NAMES and counts only. Review the output file with
 * a local editor if needed; do not paste its contents anywhere.
 *
 * Skipped (not runtime-needed on Cloud Functions):
 *   - NODE_ENV, PORT              — set by the platform
 *   - K_SERVICE, FUNCTION_TARGET, K_REVISION — injected by the platform
 *   - NEXT_PUBLIC_*               — frontend build-time variables
 *   - SMOKE_*                     — live smoke-test tooling
 *   - SUPABASE_MANAGEMENT_TOKEN   — admin CLI tooling
 *   - FIREBASE_ROOT_PASSWORD      — dev tooling
 *   - FIREBASE_SERVICE_ACCOUNT_PATH — machine-local path; use
 *     FIREBASE_SERVICE_ACCOUNT_JSON instead when the function needs admin SDK
 *     credentials without GOOGLE_APPLICATION_CREDENTIALS.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const backendDir = path.join(here, "..");
const repoRoot = path.join(backendDir, "..");

const args = process.argv.slice(2);
function flagValue(name) {
  const i = args.indexOf(name);
  return i >= 0 && args[i + 1] ? args[i + 1] : null;
}
const DRY_RUN = args.includes("--dry-run");
const SOURCE = path.resolve(flagValue("--source") ?? path.join(backendDir, ".env"));
const OUT = path.resolve(flagValue("--out") ?? path.join(repoRoot, "firebase", "functions-api", ".env.rn01-af00b"));

const EXACT_SKIP = new Set([
  "NODE_ENV",
  "PORT",
  "K_SERVICE",
  "FUNCTION_TARGET",
  "K_REVISION",
  "SUPABASE_MANAGEMENT_TOKEN",
  "FIREBASE_ROOT_PASSWORD",
  "FIREBASE_SERVICE_ACCOUNT_PATH",
]);
const PREFIX_SKIP = ["NEXT_PUBLIC_", "SMOKE_"];

// The Functions env loader reserves the FIREBASE_/X_GOOGLE_/EXT_/KIT_ prefixes
// for its own params, so these cannot appear in .env.rn01-af00b. Emit them
// under GCP_* aliases; firebase/functions-api/src/index.ts translates them
// back onto the FIREBASE_* names before any backend module reads process.env.
const RESERVED_REWRITE = new Map([
  ["FIREBASE_PROJECT_ID", "GCP_PROJECT_ID"],
  ["FIREBASE_STORAGE_BUCKET", "GCP_STORAGE_BUCKET"],
]);

function rewriteReserved(name) {
  return RESERVED_REWRITE.get(name) ?? name;
}

function shouldSkip(name) {
  return EXACT_SKIP.has(name) || PREFIX_SKIP.some((p) => name.startsWith(p));
}

/**
 * Minimal dotenv line parser: `KEY=value` (optional `export ` prefix), `#`
 * comments and blank lines ignored. The value is kept RAW (quotes/escapes
 * preserved) so it round-trips through the same dotenv semantics it had in
 * backend/.env.
 */
function parseEnvFile(text) {
  const entries = [];
  for (const rawLine of text.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith("#")) continue;
    const withoutExport = line.startsWith("export ") ? line.slice(7).trim() : line;
    const eq = withoutExport.indexOf("=");
    if (eq <= 0) continue;
    const name = withoutExport.slice(0, eq).trim();
    if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(name)) continue;
    entries.push({ name, value: withoutExport.slice(eq + 1) });
  }
  return entries;
}

if (!fs.existsSync(SOURCE)) {
  console.error(`[migrate-env] source env file not found: ${SOURCE}`);
  process.exit(1);
}

const entries = parseEnvFile(fs.readFileSync(SOURCE, "utf8"));
const kept = new Map(); // name -> raw value text (later lines win, like dotenv)
const skipped = [];
for (const { name, value } of entries) {
  if (shouldSkip(name)) {
    skipped.push(name);
    continue;
  }
  if (value.trim() === "") {
    skipped.push(name); // empty values are unset values
    continue;
  }
  kept.set(rewriteReserved(name), value);
}

const names = [...kept.keys()];
const lines = [
  "# Generated by backend/scripts/migrate-backend-env-to-functions.mjs — do not commit.",
  "# Runtime env for the `api` Cloud Function (firebase/functions-api).",
  "# This file holds secret values; it is gitignored. Names only in any log.",
  "",
  ...names.map((name) => `${name}=${kept.get(name)}`),
  "",
];

if (DRY_RUN) {
  console.log(`[migrate-env] dry run — would write ${names.length} variable(s): ${names.join(", ") || "(none)"}`);
  console.log(`[migrate-env] skipped ${skipped.length} variable(s): ${skipped.join(", ") || "(none)"}`);
  process.exit(0);
}

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, lines.join("\n"), { encoding: "utf8", mode: 0o600 });

console.log(`[migrate-env] wrote ${names.length} variable(s) to ${OUT}`);
console.log(`[migrate-env] names: ${names.join(", ") || "(none)"}`);
console.log(`[migrate-env] skipped ${skipped.length} variable(s): ${skipped.join(", ") || "(none)"}`);
