/**
 * Pull public Firebase web SDK config via Firebase CLI (no service account).
 * Writes gitignored snippets for local merge — never commit output.
 *
 * Prereqs: firebase login, project in firebase/.firebaserc (default: rn01-af00b)
 * Usage (from repo root):
 *   node backend/scripts/generate-firebase-env-from-cli.mjs
 */
import { spawnSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(__dirname, "../..");
const firebaseDir = resolve(repoRoot, "firebase");
const outPath = resolve(__dirname, "../.env.firebase.generated");

function projectId() {
  try {
    const rc = JSON.parse(readFileSync(resolve(firebaseDir, ".firebaserc"), "utf8"));
    return rc?.projects?.default?.trim() || "rn01-af00b";
  } catch {
    return "rn01-af00b";
  }
}

function runSdkConfig(pid) {
  const result = spawnSync(
    "npm",
    [
      "exec",
      "--yes",
      "firebase-tools@15.36.0",
      "--",
      "apps:sdkconfig",
      "WEB",
      "--project",
      pid,
    ],
    { cwd: firebaseDir, encoding: "utf8", maxBuffer: 2 * 1024 * 1024, shell: true },
  );
  if (result.error) throw result.error;
  const raw = `${result.stdout ?? ""}${result.stderr ?? ""}`;
  if (result.status !== 0 && !raw.includes("projectId")) {
    throw new Error(raw.trim() || `firebase apps:sdkconfig exited ${result.status}`);
  }
  const start = raw.indexOf("{");
  const end = raw.lastIndexOf("}");
  if (start < 0 || end <= start) {
    throw new Error("Could not parse apps:sdkconfig output — run: firebase login");
  }
  return JSON.parse(raw.slice(start, end + 1));
}

function main() {
  const pid = process.env.FIREBASE_PROJECT_ID?.trim() || projectId();
  let cfg;
  try {
    cfg = runSdkConfig(pid);
  } catch (err) {
    console.error(err instanceof Error ? err.message : err);
    console.error("\nNext steps:");
    console.error("  1. npm exec --yes firebase-tools@15.36.0 -- login");
    console.error("  2. Confirm firebase/.firebaserc project id");
    console.error("  3. Re-run this script");
    process.exit(1);
  }

  const lines = [
    "# Generated by backend/scripts/generate-firebase-env-from-cli.mjs",
    "# Gitignored — merge into backend/.env and frontend/.env.local manually.",
    "#",
    "# Admin: run `npm run firebase:setup` (gcloud key) or place",
    "# backend/firebase-service-account.json manually.",
    "",
    `# project: ${cfg.projectId ?? pid}`,
    `FIREBASE_PROJECT_ID=${cfg.projectId ?? pid}`,
    `FIREBASE_STORAGE_BUCKET=${cfg.storageBucket ?? ""}`,
    "",
    "# Frontend (browser) — public keys; still keep out of git commits for hygiene",
    "NEXT_PUBLIC_USE_FIREBASE_AUTH=false",
    `NEXT_PUBLIC_FIREBASE_API_KEY=${cfg.apiKey ?? ""}`,
    `NEXT_PUBLIC_FIREBASE_AUTH_DOMAIN=${cfg.authDomain ?? ""}`,
    `NEXT_PUBLIC_FIREBASE_PROJECT_ID=${cfg.projectId ?? pid}`,
    `NEXT_PUBLIC_FIREBASE_STORAGE_BUCKET=${cfg.storageBucket ?? ""}`,
    `NEXT_PUBLIC_FIREBASE_MESSAGING_SENDER_ID=${cfg.messagingSenderId ?? ""}`,
    `NEXT_PUBLIC_FIREBASE_APP_ID=${cfg.appId ?? ""}`,
    cfg.measurementId ? `NEXT_PUBLIC_FIREBASE_MEASUREMENT_ID=${cfg.measurementId}` : null,
    "",
    "# Backend Admin — set ONE of:",
    "# FIREBASE_SERVICE_ACCOUNT_JSON={\"type\":\"service_account\",...}",
    "# or FIREBASE_PROJECT_ID + FIREBASE_CLIENT_EMAIL + FIREBASE_PRIVATE_KEY",
    "",
    "# USE_FIREBASE_AUTH=false   # flip only when Admin + profile migration are ready",
  ].filter(Boolean);

  writeFileSync(outPath, `${lines.join("\n")}\n`, "utf8");
  console.log(`Wrote ${outPath}`);
  console.log("Service account: download from Firebase Console (CLI cannot mint Admin JSON).");
}

main();
