// mkpack.mjs — builds Python enhancer packs from compact data modules.
// Data module default-exports either:
//   { name, topics: [{f, title, header, rows}] }        (one pack)
//   [ { name, topics: [...] }, ... ]                    (several packs)
// rows are pipe-joined cell strings. Emits packs/<name>.py
import fs from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";

const dataPath = process.argv[2];
if (!dataPath) { console.error("usage: node mkpack.mjs <data.mjs>"); process.exit(1); }
const loaded = (await import(pathToFileURL(path.resolve(dataPath)).href)).default;
const bundles = Array.isArray(loaded) ? loaded : [loaded];

const esc = (s) => String(s).replace(/\\/g, "\\\\").replace(/"/g, '\\"');
for (const data of bundles) {
  let out = `# Conceptual classified tables — ${data.name} (gap completion pass).\n# Generated by content-tools/enhancers/bio-visuals/mkpack.mjs — edit the .mjs source, not this file.\n\ndef T(title, header, rows):\n    return {"append": True, "table": (title, header, rows)}\n\nTOPICS = [\n`;
  for (const t of data.topics) {
    const header = "[" + t.header.map((h) => `"${esc(h)}"`).join(", ") + "]";
    const rows = t.rows
      .map((r) => "     [" + r.split("|").map((c) => `"${esc(c)}"`).join(", ") + "],")
      .join("\n");
    out += ` {"file": "${esc(t.f)}",\n  "blocks": [T("${esc(t.title)}",\n    ${header},\n    [\n${rows}\n    ])]},\n`;
  }
  out += "]\n";
  const dest = path.join(process.cwd(), "packs", data.name + ".py");
  fs.writeFileSync(dest, out);
  console.log("wrote", dest, "topics:", data.topics.length);
}
