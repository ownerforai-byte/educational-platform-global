                    "R⁺ from R–Cl.\n"
                    "2. **π-complex → σ-complex (arenium ion).** The ring's π cloud attacks E⁺, forming a C–E "
                    "bond to one carbon and leaving a cyclohexadienyl cation: positive charge delocalised over "
                    "the ortho and para positions. This step is rate-determining and is where the aromaticity "
                    "is temporarily lost.\n"
                    "3. **Loss of H⁺ restores aromaticity.** FeBr₄⁻ (or HSO₄⁻) removes the proton from the "
                    "attacked carbon; the electrons flow back into the ring and the catalyst is regenerated. "
